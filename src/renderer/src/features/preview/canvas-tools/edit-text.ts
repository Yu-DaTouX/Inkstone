export function editText(lang: Lang): EditText {
  return lang === 'en-US' ? EN : ZH
}

export function editProblemText(text: EditText, error: HtmlEditError): string {
  if (error === 'conflict') return text.conflict
  if (error === 'draft') return text.draft
  if (error === 'offset' || error === 'text') return text.offsetFailed
  if (error === 'text-children') return text.textChildren
  if (error === 'styles' || error === 'attributes') return text.invalidValue
  if (error === 'empty') return text.unchanged
  if (error === 'undo') return text.undoFailed
  if (error === 'too-large') return text.tooLarge
  if (error === 'missing') return text.sourceMissing
  return text.failed
}
