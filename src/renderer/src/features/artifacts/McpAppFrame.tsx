export function readMcpAppApi(): McpAppViewApi | null {
  const yan = (window as unknown as { yan?: { mcpApps?: McpAppViewApi } }).yan
  return yan?.mcpApps ?? null
}

function windowViewport(): { width: number; height: number } {
  if (typeof window === 'undefined') return { width: 1280, height: 800 }
  return { width: window.innerWidth, height: window.innerHeight }
}

interface ConversationRect {
  top: number
  left: number
  width: number
  height: number
}

const VIEWPORT_FALLBACK = 800
const viewportListeners = new Set<() => void>()
let viewportListening = false

function readViewportHeight(): number {
  return typeof window === 'undefined' ? VIEWPORT_FALLBACK : window.innerHeight
}

function subscribeViewport(listener: () => void): () => void {
  viewportListeners.add(listener)
  if (!viewportListening && typeof window !== 'undefined') {
    window.addEventListener('resize', notifyViewport)
    viewportListening = true
  }
  return () => {
    viewportListeners.delete(listener)
    if (!viewportListeners.size && viewportListening) {
      window.removeEventListener('resize', notifyViewport)
      viewportListening = false
    }
  }
}

function notifyViewport(): void {
  for (const listener of viewportListeners) listener()
}

function useViewportHeight(): number {
  return useSyncExternalStore(subscribeViewport, readViewportHeight, () => VIEWPORT_FALLBACK)
}

export interface McpAppFrameProps {
  descriptor: Extract<McpAppViewDescriptor, { kind: 'ready' }>
  api: McpAppViewApi
  callId: string
  near?: boolean
  title?: string
  className?: string
  onClose?: () => void
}

export function McpAppFrame({
  descriptor,
  api,
  callId,
  near = true,
  title,
  className,
  onClose
}: McpAppFrameProps): JSX.Element {
  const labels = useAppLabels()
  const iframeRef = useRef<HTMLIFrameElement>(null)
  const rootRef = useRef<HTMLDivElement>(null)
  const channelRef = useRef<McpAppChannel | null>(null)
  const interactionRef = useRef<{ mode: 'drag' | 'resize'; pointerId: number; startX: number; startY: number; origin: FrameRect } | null>(null)
  const mountedRef = useRef(true)
  const returnFocusRef = useRef<HTMLElement | null>(null)

  const [form, setForm] = useState<ArtifactForm>('inline')
  const [phase, setPhase] = useState<McpAppChannelPhase>('idle')
  const [inFlight, setInFlight] = useState(0)
  const [height, setHeight] = useState(160)
  const [rawHeight, setRawHeight] = useState<number | null>(null)
  const [reload, setReload] = useState(0)
  const [pipRect, setPipRect] = useState<FrameRect | null>(null)
  const [convRect, setConvRect] = useState<ConversationRect | null>(null)
  const viewportHeight = useViewportHeight()

  const trusted = isMcpAppFrameUrl(descriptor.url)

  useEffect(() => {
    mountedRef.current = true
    return () => {
      mountedRef.current = false
    }
  }, [])

  useEffect(() => {
    const instanceId = descriptor.instanceId
    return () => {
      void Promise.resolve(api.release(instanceId)).catch(() => undefined)
    }
  }, [api, descriptor.instanceId])

  const countedApi = useMemo<McpAppDispatchApi>(
    () => ({
      dispatch: async (instanceId, message) => {
        if (mountedRef.current) setInFlight((n) => n + 1)
        try {
          return await api.dispatch(instanceId, message)
        } finally {
          if (mountedRef.current) setInFlight((n) => Math.max(0, n - 1))
        }
      }
    }),
    [api]
  )

  useEffect(() => {
    if (!trusted || !near) return undefined
    const channel = new McpAppChannel({
      instanceId: descriptor.instanceId,
      api: countedApi,
      window: window,
      getFrame: () => iframeRef.current?.contentWindow ?? null,
      loadHostContext:
        typeof api.hostContext === 'function' ? () => api.hostContext(descriptor.instanceId) : undefined,
      hooks: {
        onPhase: setPhase,
        onSizeChanged: (value) => {
          setRawHeight((current) => (current === null || Math.abs(current - value) > 1 ? value : current))
          setHeight(clampInlineHeight(value, viewportHeight))
        }
      }
    })
    channelRef.current = channel
    channel.attach()
    const unsubscribe = channel.subscribe(setPhase)
    const themeWatcher = createMcpAppThemeWatcher(
      {
        documentElement: document.documentElement,
        createObserver: (callback) =>
          typeof MutationObserver === 'function' ? new MutationObserver(callback) : null,
        matchMedia: (query) => (typeof window.matchMedia === 'function' ? window.matchMedia(query) : null)
      },
      () => channel.requestHostContext()
    )
    return () => {
      themeWatcher.dispose()
      unsubscribe()
      channel.dispose()
      channelRef.current = null
    }
  }, [trusted, near, descriptor.instanceId, countedApi, viewportHeight])

  const requestForm = useCallback(
    (next: ArtifactForm): void => {
      const active = typeof document === 'undefined' ? null : (document.activeElement as HTMLElement | null)
      if ((next === 'fullscreen' || next === 'pip') && active && active !== document.body) returnFocusRef.current = active
      if (next === 'pip') setPipRect((current) => current ?? defaultPipRect(windowViewport()))
      setForm(next)
    },
    []
  )

  const exitToInline = useCallback((): void => {
    if (onClose) onClose()
    else setForm('inline')
    const target = returnFocusRef.current
    returnFocusRef.current = null
    if (typeof window === 'undefined') return
    window.setTimeout(() => {
      if (target && target.isConnected) target.focus?.()
      else rootRef.current?.focus?.()
    }, 0)
  }, [onClose])

  useEffect(() => {
    if (form !== 'fullscreen') return undefined
    const onKey = (event: KeyboardEvent): void => {
      if (event.key !== 'Escape' || event.defaultPrevented) return
      event.preventDefault()
      event.stopPropagation()
      exitToInline()
    }
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [form, exitToInline])

  useEffect(() => {
    if (form !== 'fullscreen') return undefined
    const node = (rootRef.current?.closest?.('.v3-conv') as HTMLElement | null) ?? null
    if (!node) return undefined
    const update = (): void => {
      const rect = node.getBoundingClientRect()
      setConvRect({ top: rect.top, left: rect.left, width: rect.width, height: rect.height })
    }
    update()
    const observer = typeof ResizeObserver === 'undefined' ? null : new ResizeObserver(update)
    observer?.observe(node)
    window.addEventListener('resize', update)
    window.addEventListener('scroll', update, true)
    return () => {
      observer?.disconnect()
      window.removeEventListener('resize', update)
      window.removeEventListener('scroll', update, true)
    }
  }, [form])

  useEffect(() => {
    if (form !== 'pip') return undefined
    setPipRect((current) => current ?? defaultPipRect(windowViewport()))
    const onResize = (): void => setPipRect((current) => (current ? clampFramePosition(current, windowViewport()) : current))
    window.addEventListener('resize', onResize)
    return () => window.removeEventListener('resize', onResize)
  }, [form])

  const beginInteraction = (mode: 'drag' | 'resize') => (event: React.PointerEvent<HTMLElement>): void => {
    if (form !== 'pip' || !pipRect) return
    if (mode === 'drag' && (event.target as HTMLElement).closest('button, a, input, [role="button"]')) return
    event.preventDefault()
    event.stopPropagation()
    interactionRef.current = { mode, pointerId: event.pointerId, startX: event.clientX, startY: event.clientY, origin: pipRect }
    event.currentTarget.setPointerCapture?.(event.pointerId)
  }

  const onInteractionMove = (event: React.PointerEvent<HTMLElement>): void => {
    const interaction = interactionRef.current
    if (!interaction) return
    const dx = event.clientX - interaction.startX
    const dy = event.clientY - interaction.startY
    const viewport = windowViewport()
    setPipRect(
      interaction.mode === 'drag'
        ? moveFrame(interaction.origin, dx, dy, viewport)
        : resizeFrame(interaction.origin, dx, dy, viewport)
    )
  }

  const onHandleKeyDown = (event: React.KeyboardEvent<HTMLElement>): void => {
    if (form !== 'pip' || !pipRect) return
    const next = nudgeFrame(pipRect, event.key, { alt: event.altKey, shift: event.shiftKey }, windowViewport())
    if (!next) return
    event.preventDefault()
    event.stopPropagation()
    setPipRect(next)
  }

  const endInteraction = (event: React.PointerEvent<HTMLElement>): void => {
    if (interactionRef.current?.pointerId === event.pointerId) {
      event.currentTarget.releasePointerCapture?.(event.pointerId)
      interactionRef.current = null
    }
  }

  if (!trusted) {
    return (
      <div className={`v3-mcp-app-invalid ${className ?? ''}`} role="alert" data-testid="v3-mcp-app-invalid">
        <ShieldAlert size={16} />
        <div>
          <strong>{labels.invalidUrl}</strong>
          <p>{labels.invalidUrlHint}</p>
        </div>
      </div>
    )
  }

  const inlineOverflow = form === 'inline' && rawHeight !== null && inlineOverflows(rawHeight, viewportHeight)
  const anchorHeight = form === 'inline' ? 0 : clampInlineHeight(height, viewportHeight)

  let style: CSSProperties
  if (form === 'inline') style = { height: clampInlineHeight(height, viewportHeight) }
  else if (form === 'fullscreen') style = convRect ? { top: convRect.top, left: convRect.left, width: convRect.width, height: convRect.height } : {}
  else if (form === 'pip') style = pipRect ? { top: pipRect.y, left: pipRect.x, width: pipRect.width, height: pipRect.height } : {}
  else style = { height: '100%' }

  const statusNote = phase === 'ready' ? (inFlight > 0 ? labels.waitingApproval : null) : labels.waitingInitialize

  return (
    <>
      <div className="v3-artifact-frame-anchor" style={anchorHeight ? { height: anchorHeight } : undefined} aria-hidden />
      <div
        ref={rootRef}
        className={`v3-artifact-frame v3-mcp-app-frame v3-artifact-frame--${form} ${className ?? ''}`}
        data-testid="v3-mcp-app-frame"
        data-call-id={callId}
        data-form={form}
        data-phase={phase}
        data-overflow={inlineOverflow ? '1' : undefined}
        tabIndex={-1}
        style={style}
      >
        {form !== 'inline' ? (
          <div
            className="v3-artifact-frame-head"
            data-testid="v3-mcp-app-head"
            onPointerDown={beginInteraction('drag')}
            onPointerMove={onInteractionMove}
            onPointerUp={endInteraction}
            onPointerCancel={endInteraction}
          >
            <span className="v3-artifact-frame-title" title={title ?? descriptor.title}>{title ?? descriptor.title}</span>
            <div className="v3-artifact-frame-actions">
              {form !== 'fullscreen' ? (
                <IconButton aria-label={labels.fullscreen} title={labels.fullscreen} onPress={() => requestForm('fullscreen')}>
                  <Maximize2 size={14} />
                </IconButton>
              ) : null}
              {form !== 'pip' ? (
                <IconButton aria-label={labels.pip} title={labels.pip} onPress={() => requestForm('pip')}>
                  <PictureInPicture2 size={14} />
                </IconButton>
              ) : null}
              <IconButton aria-label={labels.reload} title={labels.reload} onPress={() => setReload((value) => value + 1)}>
                <RefreshCw size={14} />
              </IconButton>
              <IconButton aria-label={form === 'pip' ? labels.exitPip : labels.exitFullscreen} title={form === 'pip' ? labels.exitPip : labels.exitFullscreen} onPress={exitToInline}>
                {form === 'pip' ? <X size={14} /> : <Minimize2 size={14} />}
              </IconButton>
            </div>
          </div>
        ) : (
          <div className="v3-artifact-frame-tools" data-testid="v3-mcp-app-tools">
            <IconButton aria-label={labels.fullscreen} title={labels.fullscreen} onPress={() => requestForm('fullscreen')}>
              <Maximize2 size={14} />
            </IconButton>
            <IconButton aria-label={labels.pip} title={labels.pip} onPress={() => requestForm('pip')}>
              <PictureInPicture2 size={14} />
            </IconButton>
          </div>
        )}

        {near ? (
          <iframe
            ref={iframeRef}
            key={`${descriptor.instanceId}#${reload}`}
            className="v3-artifact-frame-view"
            src={descriptor.url}
            title={title ?? descriptor.title}
            sandbox={MCP_APP_FRAME_SANDBOX}
            referrerPolicy={MCP_APP_FRAME_REFERRER_POLICY}
            allow={MCP_APP_FRAME_ALLOW}
            data-testid="v3-mcp-app-iframe"
            style={form === 'inline' && inlineOverflow && rawHeight ? { height: rawHeight, flex: 'none' } : undefined}
            onLoad={() => {
              channelRef.current?.nextGeneration()
            }}
          />
        ) : (
          <div className="v3-artifact-frame-parked" role="status" data-testid="v3-mcp-app-parked">
            {labels.waitingInitialize}
          </div>
        )}

        {statusNote ? (
          <div className="v3-mcp-app-status" role="status" data-testid="v3-mcp-app-status">
            <ShieldAlert size={13} />
            <span>{statusNote}</span>
          </div>
        ) : null}

        {inlineOverflow ? (
          <div className="v3-artifact-frame-fade" data-testid="v3-mcp-app-fade">
            <Button size="sm" variant="primary" onPress={() => requestForm('fullscreen')}>
              {labels.fullscreen}
            </Button>
          </div>
        ) : null}

        {form === 'pip' ? (
          <div
            className="v3-artifact-frame-resize"
            data-testid="v3-mcp-app-resize"
            role="separator"
            tabIndex={0}
            aria-label={labels.resizeHint}
            aria-valuenow={pipRect ? pipRect.width : undefined}
            aria-valuemin={PIP_SIZE.min.width}
            aria-valuemax={PIP_SIZE.max.width}
            title={labels.resizeHint}
            onKeyDown={onHandleKeyDown}
            onPointerDown={beginInteraction('resize')}
            onPointerMove={onInteractionMove}
            onPointerUp={endInteraction}
            onPointerCancel={endInteraction}
          >
            <MoveDiagonal2 size={14} />
          </div>
        ) : null}
      </div>
    </>
  )
}

export interface McpAppResultProps {
  callId: string
  title?: string
  near?: boolean
}

export function McpAppResult({ callId, title, near = true }: McpAppResultProps): JSX.Element | null {
  const labels = useAppLabels()
  const api = useMemo(readMcpAppApi, [])
  const [descriptor, setDescriptor] = useState<McpAppViewDescriptor | null>(null)
  const [failed, setFailed] = useState(false)

  useEffect(() => {
    if (!api) return undefined
    let alive = true
    setDescriptor(null)
    setFailed(false)
    void api.prepare(callId).then(
      (next) => {
        if (!alive) {
          if (next.kind === 'ready') void Promise.resolve(api.release(next.instanceId)).catch(() => undefined)
          return
        }
        setDescriptor(next)
      },
      () => {
        if (alive) setFailed(true)
      }
    )
    return () => {
      alive = false
    }
  }, [api, callId])

  if (!api) return null
  if (failed) return <Notice tone="fail" compact className="v3-mcp-app-fallback" data-testid="v3-mcp-app-fallback">{labels.loadFailed}</Notice>
  if (!descriptor) return <Notice compact className="v3-mcp-app-fallback" data-testid="v3-mcp-app-loading">{labels.waitingInitialize}</Notice>

  const render = describeMcpAppView(descriptor)
  if (render.mode === 'text') return null
  if (render.mode === 'error') {
    return <Notice tone="fail" compact className="v3-mcp-app-fallback" data-testid="v3-mcp-app-fallback">{render.error || labels.loadFailed}</Notice>
  }
  if (render.mode === 'invalid') {
    return <Notice tone="fail" className="v3-mcp-app-invalid" data-testid="v3-mcp-app-invalid">{labels.invalidUrl}</Notice>
  }
  return (
    <McpAppFrame
      descriptor={{ kind: 'ready', instanceId: render.instanceId, url: render.url, title: render.title || title || '', callId: render.callId }}
      api={api}
      callId={callId}
      title={title}
      near={near}
    />
  )
}

const AUDIT_TONE_CLASS: Record<McpAppAuditTone, string> = {
  neutral: '',
  ask: 'ask',
  ok: 'ok',
  err: 'err'
}

function auditTime(at: number): string {
  try {
    return new Date(at).toLocaleTimeString()
  } catch {
    return ''
  }
}

export function McpAppStepAudit({ callId }: { callId: string }): JSX.Element | null {
  const labels = useAppLabels()
  const api = useMemo(readMcpAppApi, [])
  const [entries, setEntries] = useState<McpAppViewAuditEntry[] | null>(null)

  useEffect(() => {
    if (!api) return undefined
    let alive = true
    void api.audit(callId).then(
      (next) => {
        if (alive) setEntries(Array.isArray(next) ? next : [])
      },
      () => {
        if (alive) setEntries([])
      }
    )
    return () => {
      alive = false
    }
  }, [api, callId])

  if (!api || !entries || entries.length === 0) return null

  return (
    <div className="v3-mcp-app-audit" data-testid="v3-mcp-app-audit">
      <div className="v3-mcp-app-audit-title">{labels.auditTitle}</div>
      {entries.map((entry) => (
        <div className="v3-mcp-app-audit-row" key={entry.id} data-phase={entry.phase} data-testid="v3-mcp-app-audit-row">
          <span className={`v3-mcp-app-audit-phase ${AUDIT_TONE_CLASS[auditPhaseTone(entry.phase)]}`}>{entry.phase}</span>
          <span className="v3-mcp-app-audit-tool">{entry.toolName}</span>
          <span className="v3-mcp-app-audit-mode">{entry.permissionMode === 'all' ? labels.auditPermissionAll : labels.auditPermissionDanger}</span>
          <span className="v3-mcp-app-audit-summary" title={entry.summary}>{entry.summary}</span>
          <span className="v3-mcp-app-audit-time">{auditTime(entry.at)}</span>
        </div>
      ))}
    </div>
  )
}
