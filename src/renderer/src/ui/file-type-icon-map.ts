export type FileTypeIconId = (typeof FILE_TYPE_ICON_IDS)[number]

export type FileTypeTone = 'gray' | 'ink' | 'green' | 'blue' | 'yellow' | 'orange' | 'red' | 'pink' | 'purple' | 'teal' | 'brand'

