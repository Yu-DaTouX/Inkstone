;(async () => {
  const sleep = ms => new Promise(resolve => setTimeout(resolve, ms))
  const q = selector => document.querySelector(selector)
  const visible = selector => [...document.querySelectorAll(selector)].find(el => el.getClientRects().length > 0)
  const out = []
  const ok = (value, name) => out.push(`  ${value ? '✓' : '✗'} ${name}`)
  const wait = async selector => {
    for (let n = 0; n < 70 && !visible(selector); n++) await sleep(100)
    const el = visible(selector)
    if (!el) throw Error(`Missing visible ${selector}`)
    return el
  }
  const section = async id => {
    ;(await wait(`[data-testid="settings-section-${id}"]`)).click()
    await sleep(150)
  }
  const input = (el, value) => {
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(el, value)
    el.dispatchEvent(new Event('input', { bubbles: true }))
  }
  const fits = name => {
    const body = q('.settings-body')
    ok(body.scrollWidth <= body.clientWidth + 1, `${name}: no horizontal overflow`)
    const tabs = visible('.settings-jump')
    if (tabs) ok(tabs.scrollWidth <= tabs.clientWidth + 1, `${name}: section tabs fit`)
  }
  try {
    const store = window.__yanStore
    localStorage.setItem('yan.onboarded', '1')
    store.getState().openSettings('auth')
    await wait('[data-testid="cc-plugin-state"]')
    ok(!q('[data-testid="custom-api"]'), 'Custom provider form is not mounted before visiting')
    ok(visible('[data-testid="cc-install-bridge"]'), 'Missing Claude plugin has an install action')
    ok(q('#settings-tabpanel').innerText.includes('查看官方版本'), 'Claude official versions are available')
    fits('Subscriptions')
    await section('custom-api')
    ;(await wait('[data-testid="custom-api-add"]')).click()
    const id = await wait('[data-testid="custom-api-id"]')
    input(id, 'yan-unsaved-settings-probe')
    await sleep(100)
    await section('api-keys')
    ok(!visible('[data-testid="custom-api-id"]'), 'Inactive form is hidden')
    await section('custom-api')
    ok(q('[data-testid="custom-api-id"]').value === 'yan-unsaved-settings-probe', 'Unsaved draft survives section switching')
    fits('Custom provider')
    store.getState().openSettings('input')
    await wait('[data-testid="settings-section-input"][aria-selected="true"]')
    ok(!visible('[data-testid="theme-dark"]'), 'Input deep link does not show Appearance')
    await section('appearance')
    await wait('[data-testid="theme-dark"]')
    const tab = q('[data-testid="settings-section-appearance"]')
    tab.focus()
    tab.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }))
    ok(document.activeElement.dataset.testid === 'settings-section-input', 'ArrowRight moves section keyboard focus')
    fits('Appearance')
    store.getState().openSettings('context')
    await wait('[data-testid="settings-section-context"][aria-selected="true"]')
    ok(true, 'Context deep link selects Context')
    store.getState().openSettings('remote')
    await wait('[data-testid="settings-section-remote"][aria-selected="true"]')
    ok(!q('[data-testid="voice-state"]'), 'Phone deep link does not mount voice downloads')
    fits('Phone')
    store.getState().openSettings('peer')
    await wait('[data-testid="settings-section-peer"][aria-selected="true"]')
    ok(true, 'Same-page external deep link selects another device section')
    store.getState().openSettings('packages')
    await wait('[data-testid="market-pi"]')
    ok(q('[data-testid="market-pi-tab"]').getAttribute('aria-selected') === 'true', 'Legacy packages link selects pi package management')
    ok(!q('[data-testid="market-catalog"]').open, 'Package catalog is collapsed by default')
    fits('Packages')
    store.getState().openSettings('capabilities')
    await wait('[data-testid="cap-codemode"]')
    ok(!q('[data-testid="cap-ext-tools"]'), 'General capability page does not mount long search settings')
    await section('connections')
    await wait('[data-testid="cap-mcp"]')
    ok(!q('[data-testid="cap-skills-details"]').open, 'Loaded skill details are collapsed')
    fits('MCP')
    await section('external')
    await wait('[data-testid="cap-search-extension"]')
    ok(visible('[data-testid="cap-search-extension"]'), 'Extension downloads are visible even without a backend')
    ok(!q('[data-testid="cap-search-api"]').closest('details').open, 'Optional search provider forms are collapsed')
    fits('Search tools')
    for (let n = 0; n < 180 && q('[data-testid="cap-search-recheck"]').disabled; n++) await sleep(100)
    await sleep(2500)
  } catch (error) { out.push(`  ✗ Settings sections: ${String(error)}`) }
  return out.join('\n')
})()
