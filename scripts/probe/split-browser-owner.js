/** Real Electron + pi session switches + native browser. No inference or external pages. */
;(async () => {
  const lines = []
  const check = (value, label) => { lines.push(`${value ? '✓' : '✗'} ${label}`); if (!value) throw Error(label) }
  const sleep = ms => new Promise(resolve => setTimeout(resolve, ms))
  const store = window.__yanStore
  const wait = async predicate => { const end = Date.now() + 10000; while (!predicate()) { if (Date.now() > end) throw Error('wait timed out'); await sleep(50) } }
  const surface = () => document.querySelector('[data-testid="browser-surface"]')
  const column = () => surface()?.closest('[data-split-column]')?.getAttribute('data-split-column')
  try {
    await wait(() => store.getState().conn === 'ready')
    store.getState().setRailPinned(true)
    await store.getState().refreshSessions()
    const sessions = ['A', 'B', 'C'].map(label => store.getState().sessions.find(s => s.path.replaceAll('\\', '/').endsWith(`/${label}.jsonl`)))
    check(sessions.every(Boolean), '三条隔离历史会话可读')
    const [a, b, c] = sessions
    const row = session => [...document.querySelectorAll('[data-testid="rail-session"]')].find(el => el.title.includes(session.path))
    const select = async session => {
      await wait(() => !!row(session))
      row(session).click()
      await wait(() => store.getState().session?.sessionId === session.id && !store.getState().peekedPath)
      await sleep(250)
    }
    await select(a)
    await store.getState().openBrowser()
    await wait(() => !!surface() && store.getState().browserNativeVisible)
    const browserBefore = await window.yan.browser.getState()
    check(browserBefore.open, 'A 会话真实打开原生浏览器')
    row(b).dispatchEvent(new MouseEvent('click', { bubbles: true, ctrlKey: true }))
    await wait(() => document.querySelectorAll('[data-split-column]').length === 2 && column() === '0')
    const original = surface()
    await sleep(250)
    const originalBounds = (await window.yan.browser.getState()).nativeBounds
    check(column() === '0', '创建分屏后浏览器留在 A 所在左列')
    await select(b)
    check(column() === '0' && surface() === original, '点击 B 切换焦点，浏览器不迁移也不重挂载')
    const focusedBounds = (await window.yan.browser.getState()).nativeBounds
    check(originalBounds && focusedBounds && Math.abs(originalBounds.x - focusedBounds.x) <= 2, '主进程原生网页横坐标保持在原列')
    check(store.getState().browserNativeVisible, 'A 非焦点时原生网页保持可见')
    await select(c)
    check(column() === '0' && surface() === original, '左栏选择 C 替换另一列，浏览器仍属于 A')
    await select(a)
    await select(b)
    await wait(() => !surface() && !store.getState().browserNativeVisible)
    check((await window.yan.browser.getState()).open, '所属会话离开视图只隐藏，不关闭网页')
    await select(a)
    await wait(() => !!surface() && store.getState().browserNativeVisible)
    check(column() === '0', '所属会话回到视图，浏览器恢复原列')
    const browserAfter = await window.yan.browser.getState()
    check(browserAfter.activeTabId === browserBefore.activeTabId && browserAfter.url === browserBefore.url, '隐藏/恢复保留原生页签与页面')
    document.querySelector('[data-split-column="1"] [data-testid="split-head"] button:last-of-type').click()
    await wait(() => document.querySelectorAll('[data-split-column]').length === 0)
    check(!!surface(), '关闭另一列回到单会话，所属浏览器保留')
    await select(b)
    await wait(() => !surface() && !store.getState().browserNativeVisible)
    check(!surface(), '单会话切到 B，不携带 A 的浏览器')
    await select(a)
    await wait(() => !!surface() && store.getState().browserNativeVisible)
    check(!!surface(), '单会话切回 A 恢复浏览器')
    await store.getState().closeBrowser()
    await select(b)
    await store.getState().openBrowser()
    await wait(() => !!surface())
    await select(a)
    await wait(() => !surface())
    check(!surface(), '关闭后在 B 重新打开，归属正确改为 B')
    await store.getState().closeBrowser()
    await store.getState().openBrowser('file:///not-allowed')
    await select(b)
    await store.getState().openBrowser()
    await wait(() => !!surface())
    check(!!surface(), '打开失败不留下错误归属，不影响另一会话再打开')
    store.setState({ notices: [] })
    await store.getState().closeBrowser()
    await select(a)
    await store.getState().openBrowser()
    row(b).dispatchEvent(new MouseEvent('click', { bubbles: true, ctrlKey: true }))
    await select(b)
    await sleep(2200)
  } catch (error) { lines.push('✗ ' + String(error)) }
  return lines.join('\n')
})()
