export const meta = { description: '消息流里的子代理列表卡片：派 4 个假模型子代理，停掉 3 个只留 1 个运行中，截深浅与窄栏三张图，并量各行高度' }

export default async function run({ cdp, check, waitFor, sleep, shot }) {
  const ev = (expr) => cdp.evaluate(expr)
  await waitFor('s.conn === "ready"')
  await cdp.call('Emulation.setDeviceMetricsOverride', { width: 1400, height: 900, deviceScaleFactor: 1, mobile: false })
  await ev(`window.__yanStore.getState().patchSettings({ theme: 'dark', lang: 'zh-CN', permissionMode: 'all' })`)
  await ev(`window.__yanStore.getState().send('SUBAGENTS4 THENREST 先派子代理')`)
  await waitFor(`(s.subagents ?? []).filter((a) => a.status === 'running').length >= 4`, 60000)
  await sleep(3000)
  await ev(`Promise.all(window.__yanStore.getState().subagents.filter((a) => a.status === 'running').slice(1).map((a) => window.yan.subagents.stop(a.id)))`)
  await waitFor(`(s.subagents ?? []).filter((a) => a.status === 'running').length === 1`, 30000)
  await sleep(2000)
  check('四个子代理是列表而不是网格', await ev(`document.querySelectorAll('[data-testid="v3-subagent-row"]').length`) === 4)
  const heights = await ev(`[...document.querySelectorAll('[data-testid="v3-subagent-row"]')].map((row) => [row.dataset.state, Math.round(row.getBoundingClientRect().height)])`)
  console.log('行高', JSON.stringify(heights))
  check('结束的行不低于标准行高', heights.filter(([state]) => state !== 'running').every(([, h]) => h >= 26), JSON.stringify(heights))
  await ev(`document.querySelector('[data-testid="v3-subagents"]')?.scrollIntoView({ block: 'center' })`)
  await sleep(400)
  await shot('subagent-list-dark')
  await ev(`window.__yanStore.getState().patchSettings({ theme: 'light' })`)
  await sleep(500)
  await shot('subagent-list-light')
  await cdp.call('Emulation.setDeviceMetricsOverride', { width: 900, height: 900, deviceScaleFactor: 1, mobile: false })
  await sleep(600)
  await ev(`document.querySelector('[data-testid="v3-subagents"]')?.scrollIntoView({ block: 'center' })`)
  await sleep(300)
  await shot('subagent-list-narrow')
  await ev(`window.__yanStore.getState().patchSettings({ theme: 'dark' })`)
}
