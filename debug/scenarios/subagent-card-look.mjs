export const meta = { description: '消息流里的子代理卡片：假模型派 8 个子代理（多于 4 个时为网格），运行中截深浅与窄栏三张图' }

export default async function run({ cdp, check, waitFor, sleep, shot }) {
  const ev = (expr) => cdp.evaluate(expr)
  await waitFor('s.conn === "ready"')
  await cdp.call('Emulation.setDeviceMetricsOverride', { width: 1400, height: 900, deviceScaleFactor: 1, mobile: false })
  await ev(`window.__yanStore.getState().patchSettings({ theme: 'dark', lang: 'zh-CN', permissionMode: 'all' })`)
  await ev(`window.__yanStore.getState().send('SUBAGENTS8-LOOK 先派子代理，再继续')`)
  await waitFor(`(s.subagents ?? []).filter((a) => a.status === 'running').length >= 6`, 60000)
  await sleep(5000)
  check('子代理多于 4 个时卡片是网格', await ev(`document.querySelector('[data-testid="v3-subagent-list"]')?.dataset.layout === 'grid'`))
  check('网格里每个子代理一块', await ev(`document.querySelectorAll('[data-testid="v3-subagent-tile"]').length`) >= 6)
  check('块内显示当前动作', await ev(`!!document.querySelector('[data-testid="v3-subagent-tile"] .v3-sa-tile-detail')?.textContent`))
  await ev(`document.querySelector('[data-testid="v3-subagents"]')?.scrollIntoView({ block: 'start' })`)
  await sleep(400)
  await shot('subagent-card-dark')
  await ev(`window.__yanStore.getState().patchSettings({ theme: 'light' })`)
  await sleep(500)
  await shot('subagent-card-light')
  await ev(`document.querySelector('[data-testid="v3-subagent-tile"]')?.click()`)
  await sleep(800)
  check('点块在右侧打开子 Agent 面板', await ev(`!!document.querySelector('[data-testid="v3-subagent-tile"][data-selected]')`))
  await cdp.call('Emulation.setDeviceMetricsOverride', { width: 1000, height: 900, deviceScaleFactor: 1, mobile: false })
  await sleep(600)
  await ev(`document.querySelector('[data-testid="v3-subagents"]')?.scrollIntoView({ block: 'start' })`)
  await sleep(300)
  await shot('subagent-card-narrow')
  await ev(`window.__yanStore.getState().patchSettings({ theme: 'dark' })`)
}
