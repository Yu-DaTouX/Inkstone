export const meta = { demo: true, description: '新左右栏：后台 PR、可见性、分组、项目管理、搜索、草稿与无关更新开销回归' }

export default async function run({ cdp, waitFor, check, log, sleep, box, shot, fake }) {
  const ev = (expression) => cdp.evaluate(expression)
  const panelState = () => ev(`(() => { const s=window.__yanRightPanel.getState(); return s.byKey[s.key] })()`)
  const setQuery = async (value) => {
    await ev(`(() => { const el=document.querySelector('[data-testid="t3-sidebar-thread-header"] input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(value)}); el.dispatchEvent(new Event('input',{bubbles:true})); })()`)
    await sleep(350)
  }
  const select = async (testId, key) => {
    await waitFor(`!!document.querySelector('[data-testid="${testId}"] [data-key="${key}"]')`, 5000)
    await ev(`document.querySelector('[data-testid="${testId}"] [data-key="${key}"]').click()`)
    await sleep(250)
  }
  await waitFor('s.conn === "ready" && s.sessions.length >= 4')
  await cdp.call('Emulation.setDeviceMetricsOverride', { width: 1600, height: 1000, deviceScaleFactor: 1, mobile: false })
  await ev(`window.__yanStore.getState().patchSettings({lang:'zh-CN',sidebarLayout:'projects',theme:'dark'})`)
  await sleep(1200)
  await ev(`window.__yanRightPanel.getState().closeAll()`)
  await ev(`window.__yanRightPanel.getState().open({id:'pr:101',kind:'pullRequest',number:101})`)
  await sleep(80)
  await ev(`window.__yanRightPanel.getState().open({id:'logs',kind:'logs'})`)
  await waitFor(`!!window.__yanRightPanel.getState().byKey[window.__yanRightPanel.getState().key]?.surfaces.find(x=>x.id==='pr:101' && x.title)`)
  check('后台 PR 详情返回不抢日志标签', (await panelState()).active === 'logs')
  await ev(`window.__yanRightPanel.getState().setWidth(420)`)
  await sleep(100)
  const beforeWidth = await ev(`window.__yanRightPanel.getState().width`)
  await ev(`document.querySelector('[data-testid="rp"] [role="separator"]').dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowLeft',bubbles:true}))`)
  check('右栏键盘可以加宽', await ev(`window.__yanRightPanel.getState().width > ${beforeWidth}`))
  await ev(`document.querySelector('[data-testid="rp"] [role="separator"]').dispatchEvent(new KeyboardEvent('keydown',{key:'Home',bubbles:true}))`)
  check('右栏键盘 Home 回到最小宽度', await ev(`window.__yanRightPanel.getState().width===360`))
  await ev(`document.querySelector('[data-testid="rp"] [role="separator"]').dispatchEvent(new KeyboardEvent('keydown',{key:'End',bubbles:true}))`)
  check('右栏键盘 End 可展开到可用上限', await ev(`window.__yanRightPanel.getState().width>360 && window.__yanRightPanel.getState().width<=1120`))
  await ev(`(() => { const originalSet=window.setInterval,originalClear=window.clearInterval; window.__auditIntervals=new Map();window.setInterval=function(fn,ms,...args){const id=originalSet(fn,ms,...args);window.__auditIntervals.set(id,ms);return id};window.clearInterval=function(id){window.__auditIntervals.delete(id);return originalClear(id)};window.__restoreIntervals=()=>{window.setInterval=originalSet;window.clearInterval=originalClear} })()`)
  await ev(`window.__yanRightPanel.getState().open({id:'quota',kind:'quota'})`)
  await sleep(350)
  const quotaIds = await ev(`[...window.__auditIntervals.keys()]`)
  check('额度面板可见时安装轮询', quotaIds.length >= 2)
  await ev(`window.__yanRightPanel.getState().activate('logs')`)
  await sleep(250)
  const quotaHidden = await ev(`({hidden:document.querySelector('[data-testid="rp-surface-quota"]')?.hidden,remaining:${JSON.stringify(quotaIds)}.filter(id=>window.__auditIntervals.has(id))})`)
  check('额度面板隐藏后清理其轮询和时钟', quotaHidden.hidden && quotaHidden.remaining.length === 0, quotaHidden)
  const previewPath = box.demo.project.replaceAll('\\','/') + '/demo/staged.txt'
  await ev(`window.__yanRightPanel.getState().open({id:${JSON.stringify('file:'+previewPath)},kind:'file',path:${JSON.stringify(previewPath)}})`)
  await sleep(900)
  const previewIds = await ev(`[...window.__auditIntervals].filter(([,ms])=>ms===10000).map(([id])=>id)`)
  check('文件预览可见时启用文件刷新', previewIds.length > 0)
  await ev(`window.__yanRightPanel.getState().activate('logs')`)
  await sleep(250)
  check('文件预览隐藏后停止文件刷新', await ev(`${JSON.stringify(previewIds)}.every(id=>!window.__auditIntervals.has(id))`))
  await ev(`window.__restoreIntervals();window.__yanRightPanel.getState().closeAll()`)

  await ev(`(() => { const st=window.__yanStore,s=st.getState(),now=Date.now();window.__auditSessions=s.sessions;const p=s.settings.projects[0];st.setState({sessions:[...s.sessions,...Array.from({length:200},(_,i)=>({id:'audit-'+i,path:'E:/audit/'+i+'.jsonl',title:'Audit '+i,createdAt:now-i*1000,updatedAt:now-i*1000,messageCount:2,cwd:p.cwd,projectId:p.id}))]}) })()`)
  await sleep(600)
  const perf = await ev(`(async()=>{let reads=0,installs=0;const saved={};for(const key of ['offsetTop','offsetLeft','offsetWidth','offsetHeight']){const d=Object.getOwnPropertyDescriptor(HTMLElement.prototype,key);saved[key]=d;Object.defineProperty(HTMLElement.prototype,key,{...d,get(){if(this.parentElement?.matches('ul[role="tree"]'))reads++;return d.get.call(this)}})}const add=EventTarget.prototype.addEventListener;EventTarget.prototype.addEventListener=function(type,...args){if(this instanceof Element&&this.matches('ul[role="tree"]')&&type==='keydown')installs++;return add.call(this,type,...args)};try{const st=window.__yanStore;const key=Object.keys(st.getState().sessionRuntimes)[0];const original=st.getState().sessionRuntimes[key];for(let i=0;i<20;i++){st.setState({sessionRuntimes:{...st.getState().sessionRuntimes,[key]:{...original,touchedAt:Date.now()+i}}});await new Promise(requestAnimationFrame)}return{updates:20,rows:document.querySelectorAll('[data-session-path]').length,reads,installs}}finally{for(const[key,d]of Object.entries(saved))Object.defineProperty(HTMLElement.prototype,key,d);EventTarget.prototype.addEventListener=add}})()`)
  log('左栏无关更新工作量', perf)
  check('无关缓存更新不重新安装树或读取全列布局', perf.reads === 0 && perf.installs === 0, perf)
  await ev(`window.__yanStore.setState({sessions:window.__auditSessions})`)
  await sleep(250)
  await waitFor(`!!document.querySelector('[data-testid="sidebar-snoozed-shelf-toggle"]')`)
  await ev(`document.querySelector('[data-testid="sidebar-snoozed-shelf-toggle"]').click()`)
  await sleep(250)
  check('稍后分组收起保留展开入口', await ev(`document.querySelector('[data-testid="sidebar-snoozed-shelf-toggle"]')?.getAttribute('aria-expanded')==='false'`))
  await ev(`document.querySelector('[data-testid="sidebar-snoozed-shelf-toggle"]').click()`)
  await sleep(250)
  check('稍后分组可再次展开', await ev(`document.querySelector('[data-testid="sidebar-snoozed-shelf-toggle"]')?.getAttribute('aria-expanded')==='true'`))

  await setQuery('CSV')
  await ev(`document.querySelector('[data-session-path]')?.dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true}))`)
  await select('v3-session-menu', 'rename')
  await waitFor(`!!document.querySelector('[data-session-path] input')`)
  check('搜索行支持就地重命名', true)
  await ev(`(() => {const el=document.querySelector('[data-session-path] input');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,'CSV 修复验证');el.dispatchEvent(new Event('input',{bubbles:true}))})()`)
  await ev(`document.querySelector('[data-session-path] input').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}))`)
  await waitFor(`Object.values(s.manualTitles).includes('CSV 修复验证')`)
  check('搜索行改名能持久化', true)
  await setQuery('')
  await ev(`(() => {const st=window.__yanStore,s=st.getState();window.__auditSessions=s.sessions;const item=s.sessions.find(x=>x.title.includes('批量'));window.__auditSearchTarget=item;st.setState({sessions:s.sessions.filter(x=>x.id!==item.id)})})()`)
  await setQuery('批量导出')
  await waitFor(`!!document.querySelector('[data-testid="t3-sidebar-content-match"]')`)
  await ev(`document.querySelector('[data-testid="t3-sidebar-content-match"]').click()`)
  await waitFor(`s.peekedPath===window.__auditSearchTarget.path || s.session?.sessionFile===window.__auditSearchTarget.path`)
  check('全文结果可打开列表外持久化会话', true)
  await setQuery('')
  await ev(`window.__yanStore.setState({sessions:window.__auditSessions})`)
  await ev(`(() => {const s=window.__yanStore.getState();s.setSessionDraft('draft regression',s.session.sessionId)})()`)
  await waitFor(`!!document.querySelector('[data-testid="sidebar-draft-row"]')`)
  await ev(`document.querySelector('[data-testid="sidebar-draft-row"]').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true}))`)
  await select('sidebar-draft-menu', 'discard')
  check('草稿右键菜单可以丢弃草稿', await ev(`!document.querySelector('[data-testid="sidebar-draft-row"]')`))

  for (const source of ['archived','snoozed']) {
    const dropTarget = await ev(`(() => {const s=window.__yanStore.getState();return s.sessions.find(x=>${source === 'archived' ? 'x.archivedAt' : 'x.snoozedUntil>Date.now()'})?.id})()`)
    if (dropTarget) {
      await ev(`(() => {const tree=document.querySelector('ul[role="tree"]');let f=tree[Object.keys(tree).find(k=>k.startsWith('__reactFiber'))];while(f&&!f.memoizedProps?.onDropPlan)f=f.return;if(!f)throw new Error('missing sidebar drop callback');f.memoizedProps.onDropPlan({threadKey:'local:'+${JSON.stringify(dropTarget)},from:${JSON.stringify(source === 'archived' ? 'settled' : 'snoozed')},target:{section:'pinned',pinnedOrder:[],activeOrder:[]},plan:{kind:'pin'}})})()`)
      await waitFor(`s.sessions.some(x=>x.id===${JSON.stringify(dropTarget)} && x.pinned && !x.archivedAt && !x.snoozedUntil)`)
      check(`${source} 会话拖入置顶区清除来源状态`,true)
    } else check(`${source} 会话拖入置顶区清除来源状态`,false,'缺少样本')
  }

  await ev(`(() => {const st=window.__yanStore,s=st.getState();window.__auditSessions=s.sessions;window.__auditEmptyProject=s.settings.projects.find(x=>x.cwd===${JSON.stringify(box.demo.second)}).id;st.setState({sessions:s.sessions.filter(x=>x.projectId!==window.__auditEmptyProject)})})()`)
  await sleep(250)
  check('无活跃会话项目保留标题和新建入口', await ev(`!!document.querySelector('[data-sidebar-row="folder:'+CSS.escape(window.__auditEmptyProject)+'"]')`))
  await ev(`document.querySelector('[data-sidebar-row="folder:'+CSS.escape(window.__auditEmptyProject)+'"]').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true}))`)
  await select('v3-project-menu', 'rename')
  await waitFor(`!!document.querySelector('[data-testid="v3-project-name-input"]')`)
  await ev(`(() => {const el=document.querySelector('[data-testid="v3-project-name-input"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,'空项目回归');el.dispatchEvent(new Event('input',{bubbles:true}))})()`)
  await ev(`document.querySelector('[data-testid="v3-project-name-input"]').closest('form').requestSubmit()`)
  await waitFor(`s.settings.projects.some(x=>x.id===window.__auditEmptyProject&&x.name==='空项目回归')`)
  check('项目菜单改名能保存', true)
  await sleep(300)
  await ev(`document.querySelector('[data-sidebar-row="folder:'+CSS.escape(window.__auditEmptyProject)+'"]').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true}))`)
  await select('v3-project-menu', 'archive')
  await waitFor(`!!document.querySelector('[data-testid="v3-project-archive-confirm"]')`)
  await ev(`document.querySelector('[data-testid="v3-project-archive-confirm"]').click()`)
  await waitFor(`s.settings.projects.find(x=>x.id===window.__auditEmptyProject)?.archived===true`)
  await waitFor(`!!document.querySelector('[data-testid="sidebar-archived-projects"]')`)
  check('项目菜单能归档并提供归档入口', true)
  await ev(`(() => {const el=document.querySelector('[data-testid="sidebar-archived-projects"]');el.open=true;[...el.querySelectorAll('button')].find(x=>x.textContent==='空项目回归').click()})()`)
  await select('v3-project-menu', 'restore')
  await waitFor(`s.settings.projects.find(x=>x.id===window.__auditEmptyProject)?.archived===false`)
  check('归档项目可从菜单恢复', true)
  await ev(`window.__yanStore.setState({sessions:window.__auditSessions})`)
  await ev(`window.__yanStore.getState().patchSettings({sidebarLayout:'flat'})`)
  await sleep(350)
  check('平铺设置隐藏项目分组并保留项目管理入口', await ev(`!document.querySelector('[data-testid="sidebar-project-folder"]') && !!document.querySelector('[data-testid="sidebar-projects-list"]')`))
  await ev(`window.__yanStore.getState().patchSettings({sidebarLayout:'projects',theme:'light'})`)
  await sleep(350)
  check('切回项目设置恢复分组', await ev(`!!document.querySelector('[data-testid="sidebar-project-folder"]')`))
  const quoteDrag = await ev(`(() => {const row=document.querySelector('[data-sidebar-parent^="folder:"][data-session-path]');row?.scrollIntoView({block:'nearest'});const target=document.querySelector('[data-session-quote-drop]');if(!row||!target)return null;const r=row.getBoundingClientRect(),t=target.getBoundingClientRect();return{start:{x:r.left+60,y:r.top+r.height/2},end:{x:t.left+t.width/2,y:t.top+t.height/2},before:window.__yanStore.getState().attachments.length}})()`)
  if (quoteDrag) {
    await cdp.call('Input.dispatchMouseEvent', { type:'mouseMoved', ...quoteDrag.start })
    await cdp.call('Input.dispatchMouseEvent', { type:'mousePressed', button:'left', buttons:1, clickCount:1, ...quoteDrag.start })
    for (let step=1; step<=8; step++) {
      await cdp.call('Input.dispatchMouseEvent', { type:'mouseMoved', button:'left', buttons:1, x:quoteDrag.start.x+(quoteDrag.end.x-quoteDrag.start.x)*step/8, y:quoteDrag.start.y+(quoteDrag.end.y-quoteDrag.start.y)*step/8 })
      await sleep(20)
    }
    await cdp.call('Input.dispatchMouseEvent', { type:'mouseReleased', button:'left', buttons:0, clickCount:1, ...quoteDrag.end })
    await waitFor(`s.attachments.length>${quoteDrag.before}`)
    check('项目分组会话可拖入输入框作为参考附件', true)
  } else check('项目分组会话可拖入输入框作为参考附件', false, '缺少拖拽起点或输入框')
  await shot('sidebar-wiring-light')
  await ev(`window.__yanStore.getState().patchSettings({theme:'dark'})`)
  await sleep(200)
  await shot('sidebar-wiring-dark')
  check('回归未调用假模型', !fake?.requests.length)
}
