export const meta = { description: '紧凑待发卡、滚轮透传、操作栏间距、工具条三态、文字对齐和输入框缩回；隔离合成数据' }

export default async function run({ cdp, newSession, sleep, check, shot, report, waitFor }) {
  const ev = (code) => cdp.evaluate(code)
  const user = { id: 'compact-user', role: 'user', text: '界面交互回归', timestamp: Date.now() - 20000 }
  await newSession()
  await ev(`window.__yanStore.getState().patchSettings({theme:'light',lang:'zh-CN',density:'comfortable',rightPanelOpen:false,promptSuggestions:false,reduceMotion:false,composerHeight:undefined})`)
  const inject = async (messages, live = true, extra = {}) => {
    await ev(`(()=>{const s=window.__yanStore.getState();window.__yanStore.setState({messages:${JSON.stringify(messages)},session:{...s.session,isAgentRunning:${live},isStreaming:${live}},historyLoading:false,switchLoading:false,...${JSON.stringify(extra)}})})()`)
    await sleep(400)
  }
  const calls = Array.from({length:8}, (_, i) => ({id:'compact-tool-'+i,name:'bash',args:{command:'fixture-'+i,description:'检查 '+i},status:i===7?'running':'ok',startedAt:Date.now()-3000}))
  await inject([user,{id:'compact-tools',role:'assistant',text:'',toolCalls:calls}])
  const steps = () => ev(`document.querySelectorAll('[data-testid="v3-process-body"] [data-testid="v3-step"]').length`)
  const toggle = async () => { await ev(`document.querySelector('[data-testid="v3-process-toggle"]').click()`); await sleep(450) }
  const recent = await steps()
  check('工具条初始短显示仅保留最近调用', recent===3, recent)
  check('没有重复的前面调用展开按钮', await ev(`!document.querySelector('[data-testid="v3-tools-earlier"], [data-testid="v3-process-more"]')`))
  await toggle()
  const all = await steps()
  check('点击短工具条完全展开所有调用', all===8, all)
  await toggle()
  check('再次点击工具条完全折叠', await ev(`document.querySelector('[data-testid="v3-process-toggle"]').getAttribute('aria-expanded')==='false'`))
  await toggle()
  check('第三次点击回到短显示', await steps()===3 && await ev(`document.querySelector('[data-testid="v3-process-body"]').dataset.stage==='true'`))
  await shot('process-recent-light')

  const narration = {id:'compact-narration',role:'assistant',text:'进度文字的字号应当保持一致。'}
  await inject([user,narration])
  const proseSize = () => ev(`getComputedStyle([...document.querySelectorAll('.v3-prose')].find(e=>e.textContent.includes('进度文字的字号'))).fontSize`)
  const liveFont = await proseSize()
  await inject([user,{...narration,toolCalls:[calls[7]]}])
  const completedFont = await proseSize()
  const bodyFont = await ev(`getComputedStyle(document.documentElement).getPropertyValue('--d-prose').trim()`)
  check('进度文字从流式正文变为过程文字后字号不缩小', liveFont===completedFont&&completedFont===bodyFont, {liveFont,completedFont,bodyFont})

  await inject([user,{id:'compact-error',role:'assistant',text:'',error:'fixture model error'}],false)
  await cdp.call('Input.dispatchMouseEvent',{type:'mouseMoved',x:5,y:5})
  await sleep(900)
  const actions = await ev(`(()=>{const a=document.querySelector('[data-testid="v3-user-actions"]'),b=a.querySelector('button'),m=document.querySelector('[data-turn-id="compact-error"]');return {opacity:getComputedStyle(b).opacity,gap:m.getBoundingClientRect().top-a.getBoundingClientRect().bottom}})()`)
  check('用户消息按钮移开鼠标后隐藏', Number(actions.opacity)===0, actions)
  check('模型消息与用户操作栏之间留出间距', actions.gap>=6, actions)
  const hoverPoint = await ev(`(()=>{const r=document.querySelector('.v3-msg.user').getBoundingClientRect();return {x:r.left+12,y:r.top-12}})()`)
  await cdp.call('Input.dispatchMouseEvent',{type:'mouseMoved',...hoverPoint})
  await sleep(300)
  check('用户消息上方12px的邻近区域也能触发按钮', await ev(`getComputedStyle(document.querySelector('[data-testid="v3-user-actions"] button')).opacity==='1'`))
  await shot('user-actions-hover-light')
  await cdp.call('Input.dispatchMouseEvent',{type:'mouseMoved',x:5,y:5})
  await sleep(900)
  await ev(`document.querySelector('[data-testid="v3-msg-copy"]').focus()`)
  await sleep(250)
  check('键盘聚焦用户消息按钮时可见',await ev(`getComputedStyle(document.querySelector('[data-testid="v3-msg-copy"]')).opacity==='1'`))
  await ev(`document.activeElement.blur()`)

  await inject([user,{id:'align-before',role:'assistant',text:'',toolCalls:[{...calls[0],name:'codemode',args:{code:'fixture'}}]},{id:'align-thinking',role:'assistant',text:'',thinking:'Reading model methods, tests',thinkingMs:4000,toolCalls:[{...calls[1],name:'codemode',args:{code:'fixture'}}]}],false)
  await ev(`document.querySelector('[data-testid="v3-process-toggle"][aria-expanded="false"]')?.click()`)
  await sleep(450)
  const thinkAlignment = await ev(`(()=>{const think=document.querySelector('[data-testid="v3-thinking-toggle"]'),command=document.querySelector('[data-testid="v3-step"]'),brain=think.querySelector('.ui-collapsible__icon').getBoundingClientRect(),code=command.querySelector('.ui-collapsible__icon').getBoundingClientRect(),line=think.querySelector('.v3-step-line'),arrow=line.querySelector('.ui-chevron'),label=line.querySelector('.v3-step-label'),peek=line.querySelector('[data-testid="v3-thinking-peek"]');return {brain:brain.x+brain.width/2,code:code.x+code.width/2,inline:!!arrow&&label.getBoundingClientRect().right<=arrow.getBoundingClientRect().left&&arrow.getBoundingClientRect().right<=peek.getBoundingClientRect().left}})()`)
  check('思考图标与命令图标水平对齐',Math.abs(thinkAlignment.brain-thinkAlignment.code)<0.6,thinkAlignment)
  check('折叠箭头位于思考用时后、内容预览前',thinkAlignment.inline,thinkAlignment)
  await shot('thinking-aligned-light')
  await ev(`document.querySelector('[data-testid="v3-thinking-toggle"]').click()`)
  await sleep(350)
  check('思考仍可点击展开完整内容',await ev(`document.querySelector('[data-testid="v3-thinking-toggle"]').getAttribute('aria-expanded')==='true'&&document.querySelector('[data-testid="v3-thinking-body"]').textContent.includes('Reading model methods')`))
  await ev(`document.querySelector('[data-testid="v3-thinking-toggle"]').click()`)
  await sleep(350)
  check('思考仍可再次折叠并保留预览',await ev(`document.querySelector('[data-testid="v3-thinking-toggle"]').getAttribute('aria-expanded')==='false'&&!!document.querySelector('[data-testid="v3-thinking-peek"]')`))
  await ev(`window.__yanStore.getState().patchSettings({theme:'dark'})`)
  await cdp.call('Emulation.setDeviceMetricsOverride',{width:720,height:900,deviceScaleFactor:1,mobile:false})
  await sleep(450)
  check('深色窄窗思考预览与折叠按钮不横向溢出',await ev(`document.documentElement.scrollWidth<=innerWidth+1&&document.querySelector('.v3-stream').scrollWidth<=document.querySelector('.v3-stream').clientWidth+1`))
  await shot('thinking-aligned-dark-narrow')
  await cdp.call('Emulation.clearDeviceMetricsOverride')
  await ev(`window.__yanStore.getState().patchSettings({theme:'light'})`)

  const long = Array.from({length:35},(_,i)=>'消息流段落 '+i+'。保持滚动测试内容。').join('\n\n')
  const queueText = Array.from({length:8},(_,i)=>'待发长文字第'+i+'行。').join('\n')+'\n\n（附图按添加顺序编号：图1、图2、图3）'
  await inject([user,{id:'compact-long',role:'assistant',text:long}],false,{queue:{steering:[{id:'compact-steer',text:queueText}],followUp:[{id:'compact-follow',text:queueText}]}})
  await sleep(600)
  const queueMetrics = await ev(`(()=>{const q=document.querySelector('[data-testid="queue-stack"]'),p=q.querySelector('.t3-queue__text');return {text:p.textContent,height:p.getBoundingClientRect().height,line:parseFloat(getComputedStyle(p).lineHeight),actions:[...q.querySelectorAll('.t3-queue__actions')].map(e=>getComputedStyle(e).opacity)}})()`)
  check('插话和排队卡正文最多三行', queueMetrics.height<=queueMetrics.line*3+2, queueMetrics)
  check('待发卡不显示附图编号括号说明', !queueMetrics.text.includes('附图按添加顺序编号'))
  check('插话排队卡按钮常显', queueMetrics.actions.every(v=>Number(v)===1))
  const wheelAt = async (point) => {
    await ev(`(()=>{const s=document.querySelector('.v3-stream');s.dispatchEvent(new WheelEvent('wheel',{deltaY:-1,bubbles:true}));s.scrollTop=Math.min(300,s.scrollHeight-s.clientHeight)})()`)
    await sleep(180)
    const before = await ev(`document.querySelector('.v3-stream').scrollTop`)
    await cdp.call('Input.dispatchMouseEvent',{type:'mouseMoved',...point})
    await cdp.call('Input.dispatchMouseEvent',{type:'mouseWheel',...point,deltaY:150,deltaX:0})
    await sleep(250)
    return {before,after:await ev(`document.querySelector('.v3-stream').scrollTop`)}
  }
  const points = await ev(`(()=>{const q=document.querySelector('[data-testid="queue-stack"]'),r=q.getBoundingClientRect(),b=q.querySelector('.t3-queue__bubble').getBoundingClientRect();return {card:{x:b.x+b.width/2,y:b.y+b.height/2},gap:{x:r.x+3,y:b.y+b.height/2}}})()`)
  const cardWheel = await wheelAt(points.card)
  check('鼠标停在待发卡上也能滚动消息流',cardWheel.after>cardWheel.before+10,cardWheel)
  const gapWheel = await wheelAt(points.gap)
  check('待发卡同高度空白处不挡消息流滚轮',gapWheel.after>gapWheel.before+10,gapWheel)
  await shot('queue-compact-light')
  report.queue = {queueMetrics,cardWheel,gapWheel}

  await ev(`window.__yanStore.setState({queue:{steering:[],followUp:[]}})`)
  const model = {id:'fixture-model',name:'GPT-6.1 Sol',provider:'debug',api:'openai-responses',reasoning:true,contextWindow:200000,maxTokens:10000,input:['text'],cost:{input:0,output:0,cacheRead:0,cacheWrite:0}}
  await ev(`(()=>{const s=window.__yanStore.getState();window.__yanStore.setState({models:[${JSON.stringify(model)}],session:{...s.session,model:${JSON.stringify(model)},thinkingLevel:'high',thinkingLevelsStatus:'known',availableThinkingLevels:['off','low','medium','high']},settings:{...s.settings,defaultModel:'debug/fixture-model'}})})()`)
  await sleep(500)
  const alignment = await ev(`(()=>{const measure=(selector)=>{const e=document.querySelector(selector);if(!e?.firstChild)return null;const r=document.createRange();r.selectNode(e.firstChild);const b=r.getBoundingClientRect();return {top:b.top,bottom:b.bottom,height:b.height}};return {model:measure('[data-chat-provider-model-picker-label]'),effort:measure('[data-composer-effort-label]')}})()`)
  check('模型名与High思考档位文字垂直对齐',!!alignment.model&&!!alignment.effort&&Math.abs(alignment.model.top-alignment.effort.top)<0.6&&await ev(`document.querySelector('[data-composer-effort-label]')?.firstChild?.textContent==='High'`),alignment)
  await shot('model-effort-light')
  report.alignment = alignment

  await inject([user,{id:'compact-height',role:'assistant',text:long}],true)
  await ev(`(()=>{const s=document.querySelector('.v3-stream');s.dispatchEvent(new WheelEvent('wheel',{deltaY:100000,bubbles:true}));s.scrollTop=s.scrollHeight})()`)
  const metrics = () => ev(`(()=>{const stream=document.querySelector('.v3-stream'),tail=document.querySelector('[data-turn-id="compact-height"]'),composer=document.querySelector('[data-testid="composer-v3"]');return {top:tail.getBoundingClientRect().top,scroll:stream.scrollTop,scrollHeight:stream.scrollHeight,composer:composer.getBoundingClientRect().height,padding:parseFloat(getComputedStyle(stream.firstElementChild).paddingBottom),editor:document.querySelector('[data-testid="composer-input"]').getBoundingClientRect().height}})()`)
  await ev(`window.__yanStore.setState({editorInject:{text:'',mode:'replace',id:Date.now()}})`)
  await sleep(650)
  const beforeHeight = await metrics()
  await ev(`window.__yanStore.setState({editorInject:{text:${JSON.stringify(Array.from({length:18},(_,i)=>'大段文字 '+i).join('\n'))},mode:'replace',id:Date.now()}})`)
  await sleep(650)
  const tallText = await metrics()
  await ev(`window.__yanStore.setState({editorInject:{text:'',mode:'replace',id:Date.now()}})`)
  await sleep(750)
  const shortText = await metrics()
  check('大段输入清空后输入框和消息流自动回落',Math.abs(shortText.composer-beforeHeight.composer)<2&&Math.abs(shortText.top-beforeHeight.top)<3,{beforeHeight,tallText,shortText})
  const handle = '[data-composer-height-handle="true"]'
  const point = await ev(`(()=>{const r=document.querySelector('${handle}').getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()`)
  await cdp.call('Input.dispatchMouseEvent',{type:'mouseMoved',...point})
  await cdp.call('Input.dispatchMouseEvent',{type:'mousePressed',...point,button:'left',clickCount:1})
  await cdp.call('Input.dispatchMouseEvent',{type:'mouseMoved',x:point.x,y:point.y-220,button:'left',buttons:1})
  await cdp.call('Input.dispatchMouseEvent',{type:'mouseReleased',x:point.x,y:point.y-220,button:'left',clickCount:1})
  await sleep(650)
  const tallManual = await metrics()
  await ev(`document.querySelector('${handle}').dispatchEvent(new MouseEvent('dblclick',{bubbles:true}))`)
  await sleep(750)
  const resetManual = await metrics()
  check('手动拉高后双击还原，消息流也回到原位',Math.abs(resetManual.composer-beforeHeight.composer)<2&&Math.abs(resetManual.top-beforeHeight.top)<3,{beforeHeight,tallManual,resetManual})
  await shot('composer-height-restored-light')
  report.height = {beforeHeight,tallText,shortText,tallManual,resetManual}
  await ev(`window.__yanStore.getState().patchSettings({theme:'dark'})`)
  await cdp.call('Emulation.setDeviceMetricsOverride',{width:720,height:900,deviceScaleFactor:1,mobile:false})
  await sleep(450)
  check('深色窄窗不横向溢出',await ev(`document.documentElement.scrollWidth<=innerWidth+1`))
  await shot('compact-dark-narrow')
}
